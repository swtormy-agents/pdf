#!/usr/bin/env python3
"""Copies the current strings from their owners into tools/i18n/ (run by gen.py on every build, so FAQ, SEO and UI
strings are always read fresh). Sources (read-only, never edited here):
  UI strings  /workspace/i18n/pdf-tool/{en,ru,zh}.json            (Nathan Price, generated by his build.py)
  SEO ru/zh   /workspace/i18n/pdf-tool/seo/seo-ru-zh.json          (Nathan Price)
  SEO en      /workspace/seo/pdf-tool-keywords-structure.md §8 en  (Lucas Gray)
  FAQ         /workspace/seo/pdf-tool-faq-en.md, /workspace/i18n/pdf-tool/faq/faq-{ru,zh}.md
  Privacy     /workspace/company/legal/pdf-privacy-disclaimer.md   (Sarah Mitchell)
  Header/legal line + pair_h1 (HEIC link anchor): /workspace/local-image-converter/tools/i18n/{lang}.json (same component as the converter)
Only public text is extracted (no author notes). If a source dir is missing (e.g. CI), the committed copies are used."""
import os,re,json,sys
os.chdir(os.path.join(os.path.dirname(__file__),'..'))
W=os.environ.get('PDF_SRC_ROOT','/workspace')
I18N=f'{W}/i18n/pdf-tool'; OUT='tools/i18n'
LANGS=['en','ru','zh']
SLUG={'merge-pdf':'merge','split-pdf':'split','organize-pdf':'organize','jpg-to-pdf':'jpg'}
def dump(name,obj):
    s=json.dumps(obj,ensure_ascii=False,indent=1,sort_keys=False)+'\n'
    p=f'{OUT}/{name}'
    if not os.path.exists(p) or open(p,encoding='utf-8').read()!=s: open(p,'w',encoding='utf-8').write(s)
def faq(path,qp,ap):
    out={};cur=None;q=None
    for line in open(path,encoding='utf-8').read().splitlines():
        if line.startswith('## '):
            m=re.search(r'/pdf/(?:(?:ru|zh)/)?([a-z-]+)\.html',line)
            cur=SLUG[m.group(1)] if m else ('hub' if re.search(r'/pdf/(?:ru/|zh/)?\s',line+' ') else None)
            if cur: out[cur]=[]
            continue
        if cur is None: continue
        m=re.fullmatch(r'\*\*'+qp+r'\s*(.+?)\*\*',line.strip())
        if m: q=m.group(1).strip(); continue
        m=re.fullmatch(ap+r'\s*(.+)',line.strip())
        if m and q: out[cur].append({'q':q,'a':m.group(1).strip()}); q=None
    assert set(out)=={'hub','merge','split','organize','jpg'}, (path,list(out))
    return out
def seo_en(path):
    s=open(path,encoding='utf-8').read(); sec=s.split('### en',1)[1].split('###',1)[0]; out={}
    for row in sec.splitlines():
        c=[x.strip() for x in row.strip().strip('|').split('|')]
        if len(c)==4 and c[0] in ('hub','merge','split','organize','jpg'): out[c[0]]={'title':c[1],'h1':c[2],'meta':c[3]}
    assert len(out)==5; return out
def privacy(path):
    s=open(path,encoding='utf-8').read(); out={}
    for l,hp,hd in (('en','## EN — Privacy notice','## EN — Disclaimer'),('ru','## RU — Уведомление о конфиденциальности','## RU — Отказ от ответственности'),('zh','## ZH — 隐私声明','## ZH — 免责声明')):
        def block(h):
            b=s.split(h,1)[1]; b=re.split(r'\n---\n|\n## ',b,maxsplit=1)[0]
            return [p.strip() for p in b.strip().split('\n\n') if p.strip()]
        out[l]={'privacy':block(hp),'disclaimer':block(hd)}
    return out
def main():
    if not os.path.isdir(I18N): print('sync_i18n: sources not found, using committed tools/i18n/'); return
    os.makedirs(OUT,exist_ok=True)
    for l in LANGS: dump(f'{l}.json',json.load(open(f'{I18N}/{l}.json',encoding='utf-8')))
    seo=json.load(open(f'{I18N}/seo/seo-ru-zh.json',encoding='utf-8')); seo['en']=seo_en(f'{W}/seo/pdf-tool-keywords-structure.md')
    dump('seo.json',{l:seo[l] for l in LANGS})
    dump('faq.json',{'en':faq(f'{W}/seo/pdf-tool-faq-en.md','Q:','A:'),'ru':faq(f'{I18N}/faq/faq-ru.md','В:','О:'),'zh':faq(f'{I18N}/faq/faq-zh.md','问：','答：')})
    dump('privacy.json',privacy(f'{W}/company/legal/pdf-privacy-disclaimer.md'))
    # pair_h1: the converter's H1 pattern for its pair pages, used as the anchor of the jpg-to-pdf -> heic-to-jpg link
    keys=['lang_code','lang_nav','theme','system','light','dark','settings_aria_system','settings_aria_light','settings_aria_dark','settings_aria_mobile','legal','pair_h1']
    dump('header.json',{l:{k:json.load(open(f'{W}/local-image-converter/tools/i18n/{l}.json',encoding='utf-8'))[k] for k in keys} for l in LANGS})
    print('sync_i18n: ok')
if __name__=='__main__': main()
