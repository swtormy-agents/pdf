#!/usr/bin/env python3
"""Checker for interlinking spec 2026-10 §5 AC1–AC9 as they apply to the pdf repo.

AC2 (home Popular links) is out of scope here (home is generated by genhome.py).
Run from repo root or tools/: python3 tools/test/check-interlinking.py
Exit 0 only if every applicable check passes. Re-running gen.py must leave HTML unchanged."""
import hashlib, html, json, os, re, subprocess, sys
from collections import Counter
from urllib.parse import urlparse

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
os.chdir(ROOT)
LANGS = ['en', 'ru', 'zh']
PAGES = ['index.html', 'merge-pdf.html', 'split-pdf.html', 'organize-pdf.html',
         'jpg-to-pdf.html', 'privacy.html', 'licenses.html']
CSP = ("default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' blob:; "
       "worker-src 'self'; base-uri 'none'; form-action 'none'; object-src 'none'")
ALLOWED_HOSTS = {'', 'noclaudkit.com', 'github.com', 'docs.github.com', 'schema.org', 'www.w3.org'}
FT_HREFS = {
    'en': ['/', '/image-converter/', '/pdf/', '/image-converter/heic-to-jpg.html',
           'merge-pdf.html', 'split-pdf.html', 'jpg-to-pdf.html'],
    'ru': ['/ru/', '/image-converter/ru/', '/pdf/ru/', '/image-converter/ru/heic-to-jpg.html',
           'merge-pdf.html', 'split-pdf.html', 'jpg-to-pdf.html'],
    'zh': ['/zh/', '/image-converter/zh/', '/pdf/zh/', '/image-converter/zh/heic-to-jpg.html',
           'merge-pdf.html', 'split-pdf.html', 'jpg-to-pdf.html'],
}
FT_LABELS = {
    'en': ['NoClaudKit', 'Image converter', 'PDF tools', 'HEIC to JPG', 'Merge PDF', 'Split PDF', 'JPG to PDF'],
    'ru': ['NoClaudKit', 'Конвертер изображений', 'Инструменты для PDF', 'HEIC в JPG', 'Объединить PDF', 'Разделить PDF', 'JPG в PDF'],
    'zh': ['NoClaudKit', '图片转换器', 'PDF 工具', 'HEIC 转 JPG', '合并 PDF', '拆分 PDF', '图片转 PDF'],
}
CANON = {
    'en': 'https://noclaudkit.com/pdf/',
    'ru': 'https://noclaudkit.com/pdf/ru/',
    'zh': 'https://noclaudkit.com/pdf/zh/',
}
HREFLANG = {'en': 'en', 'ru': 'ru', 'zh': 'zh-Hans'}
NB = '\u00a0'
FAILS = []

def lp(lang):
    return '' if lang == 'en' else lang + '/'

def path_of(lang, page):
    return lp(lang) + page

def load(lang, page):
    return open(path_of(lang, page), encoding='utf-8').read()

def fail(ac, msg):
    FAILS.append(f'AC{ac}: {msg}')
    print('FAIL', f'AC{ac}: {msg}')

def ok(ac, msg):
    print('PASS', f'AC{ac}: {msg}')

def norm(s):
    return re.sub(r'\s+', ' ', html.unescape(s).replace(NB, ' ').replace('\u2011', '-')).strip()

def site_lang(path):
    parts = [p for p in path.split('/') if p]
    if not parts:
        return 'en'
    if parts[0] in ('ru', 'zh'):
        return parts[0]
    if parts[0] in ('image-converter', 'pdf'):
        if len(parts) > 1 and parts[1] in ('ru', 'zh'):
            return parts[1]
        return 'en'
    return None

def href_path(href):
    if href.startswith('https://noclaudkit.com'):
        return urlparse(href).path or '/'
    if href.startswith('/'):
        return href.split('?', 1)[0]
    return None

def is_switcher(tag):
    return 'hreflang=' in tag or 'Read in English' in tag

def each_anchor(s):
    for m in re.finditer(r'<a\b([^>]*)>(.*?)</a>', s, re.S):
        yield m.group(1), m.group(2)

def each_page():
    for lang in LANGS:
        for page in PAGES:
            yield lang, page, load(lang, page)

def ac1():
    bad = []
    for lang, page, s in each_page():
        ft = re.search(r'<nav class="ft"[^>]*>(.*?)</nav>', s, re.S)
        if not ft:
            bad.append(f'{lang}/{page}: no .ft nav'); continue
        hrefs = re.findall(r'<a href="([^"]*)"', ft.group(1))
        texts = [norm(re.sub(r'<[^>]+>', '', x)) for x in re.findall(r'<a\b[^>]*>(.*?)</a>', ft.group(1), re.S)]
        if hrefs != FT_HREFS[lang]:
            bad.append(f'{lang}/{page}: footer hrefs {hrefs}')
        if texts != FT_LABELS[lang]:
            bad.append(f'{lang}/{page}: footer labels {texts}')
        home = re.search(r'<nav class="ft"[^>]*>.*?<a href="([^"]*)"[^>]*>NoClaudKit</a>', s, re.S)
        if not home or home.group(1) != FT_HREFS[lang][0]:
            bad.append(f'{lang}/{page}: missing same-language home link')
        for tag, _inner in each_anchor(s):
            hm = re.search(r'href="([^"]*)"', tag)
            if not hm or is_switcher(tag):
                continue
            href = hm.group(1)
            path = href_path(href)
            if path is None:
                continue
            hl = site_lang(path)
            if hl and hl != lang:
                bad.append(f'{lang}/{page}: cross-language href {href}')
    if bad:
        for b in bad:
            fail(1, b)
    else:
        ok(1, '21 pages have the 7-link same-language footer and no cross-language hrefs outside the switcher')

def ac3():
    bad = []
    for lang in LANGS:
        merge = load(lang, 'merge-pdf.html')
        cx = re.search(r'<p class="cross[^"]*"[^>]*>(.*?)</p>', merge, re.S)
        if not cx or 'href="jpg-to-pdf.html"' not in cx.group(0):
            bad.append(f'{lang}/merge-pdf.html: missing contextual jpg-to-pdf')
        elif cx.group(0).count('href="jpg-to-pdf.html"') != 1:
            bad.append(f'{lang}/merge-pdf.html: expected exactly one contextual jpg-to-pdf href')
        jpg = load(lang, 'jpg-to-pdf.html')
        if 'heic-to-jpg.html' not in jpg:
            bad.append(f'{lang}/jpg-to-pdf.html: heic-to-jpg link missing')
        for page in ('merge-pdf.html', 'split-pdf.html', 'organize-pdf.html'):
            if 'heic-to-jpg' in load(lang, page).split('<footer', 1)[0]:
                bad.append(f'{lang}/{page}: heic-to-jpg in body')
    if bad:
        for b in bad:
            fail(3, b)
    else:
        ok(3, 'merge-pdf → jpg-to-pdf once; jpg-to-pdf keeps heic-to-jpg; no body heic links on merge/split/organize')

def ac4():
    bad = []
    skip_hash = {'#', '#main', '#dl'}
    for lang, page, s in each_page():
        for tag, _inner in each_anchor(s):
            hm = re.search(r'href="([^"]*)"', tag)
            if not hm:
                continue
            href = hm.group(1)
            if 'rel="nofollow"' in tag or 'onclick=' in tag:
                bad.append(f'{lang}/{page}: nofollow/onclick on {href}')
            if re.search(r'[?&]utm_|[?&]ref=', href, re.I):
                bad.append(f'{lang}/{page}: utm/ref on {href}')
            if '#' in href and href.split('?', 1)[0] not in skip_hash and not href.endswith(tuple(skip_hash)):
                frag = '#' + href.split('#', 1)[1]
                if frag not in skip_hash:
                    bad.append(f'{lang}/{page}: hash href {href}')
            if href in ('merge-pdf.html', 'split-pdf.html', 'organize-pdf.html', 'jpg-to-pdf.html',
                        'privacy.html', 'licenses.html', './'):
                dest = path_of(lang, 'index.html' if href == './' else href)
                if not os.path.isfile(dest):
                    bad.append(f'{lang}/{page}: missing file for {href}')
            path = href_path(href)
            if path:
                if path.rstrip('/') in ('/pdf', '/pdf/ru', '/pdf/zh') or path.startswith('/pdf/'):
                    local = 'index.html' if path.endswith('/') or path.rstrip('/').endswith(('pdf', 'ru', 'zh')) and not path.endswith('.html') else os.path.basename(path)
                    if path.endswith('/') or re.fullmatch(r'/pdf(?:/(?:ru|zh))?/?', path):
                        local = lp(site_lang(path) or 'en') + 'index.html'
                    elif path.endswith('.html'):
                        local = ('' if site_lang(path) == 'en' else site_lang(path) + '/') + os.path.basename(path)
                    if local and not os.path.isfile(local):
                        bad.append(f'{lang}/{page}: pdf href {href} -> missing {local}')
                if re.search(r'/(image-converter|pdf)?/?$', path) or path.endswith('/'):
                    if not path.endswith('/') and site_lang(path) is not None and not path.endswith('.html'):
                        bad.append(f'{lang}/{page}: hub href missing trailing slash: {href}')
    if bad:
        for b in bad[:40]:
            fail(4, b)
    else:
        ok(4, 'no utm/ref/# (except #main/#dl), no nofollow/onclick; in-repo hrefs resolve')

def ac5():
    bad = []
    banned = re.compile(r'\b(free|online|without upload|онлайн)\b', re.I)
    for lang, page, s in each_page():
        # R3: interlinking surfaces (footer + breadcrumbs + contextual body). Mode tabs/cards
        # keep pre-existing short labels; zh mode_images already equals Nathan's «图片转 PDF».
        body = re.sub(r'<script[^>]*>.*?</script>', '', s, flags=re.S)
        texts = []
        for sel in (r'<nav class="ft"[^>]*>.*?</nav>', r'<nav class="crumbs"[^>]*>.*?</nav>',
                    r'<p class="cross[^"]*"[^>]*>.*?</p>'):
            block = re.search(sel, body, re.S)
            if not block:
                continue
            for m in re.finditer(r'<a\b[^>]*>(.*?)</a>', block.group(0), re.S):
                t = norm(re.sub(r'<[^>]+>', '', m.group(1)))
                if t:
                    texts.append(t)
            for sm in re.finditer(r'<span aria-current="page">(.*?)</span>', block.group(0), re.S):
                t = norm(re.sub(r'<[^>]+>', '', sm.group(1)))
                if t:
                    texts.append(t)
        for m in re.finditer(r'<a\b[^>]*>(.*?)</a>', body, re.S):
            t = norm(re.sub(r'<[^>]+>', '', m.group(1)))
            if t and banned.search(t):
                bad.append(f'{lang}/{page}: banned word in anchor {t!r}')
        for t, n in Counter(texts).items():
            if n > 2:
                bad.append(f'{lang}/{page}: anchor {t!r} appears {n}×')
        for t in texts:
            if banned.search(t):
                bad.append(f'{lang}/{page}: banned word in interlink anchor {t!r}')
    if bad:
        for b in bad:
            fail(5, b)
    else:
        ok(5, 'no exact anchor > 2× (nav+footer+body+crumbs); no free/online in anchors')

def ac6():
    bad = []
    for lang, page, s in each_page():
        if '<main' not in s or '<nav class="crumbs"' not in s.split('<main', 1)[1].split('</main>', 1)[0]:
            bad.append(f'{lang}/{page}: breadcrumbs not inside <main>')
        raw = re.findall(r'<script type="application/ld\+json">(.*?)</script>', s, re.S)
        types = []
        crumb_ld = None
        for j in raw:
            if '<' in j or '>' in j:
                bad.append(f'{lang}/{page}: raw < or > in JSON-LD (need \\u003c)')
            try:
                d = json.loads(j)
            except json.JSONDecodeError as e:
                bad.append(f'{lang}/{page}: invalid JSON-LD ({e})'); continue
            types.append(d.get('@type'))
            if d.get('@type') == 'BreadcrumbList':
                crumb_ld = d
            if NB in j:
                bad.append(f'{lang}/{page}: NBSP in JSON-LD')
        if 'BreadcrumbList' not in types:
            bad.append(f'{lang}/{page}: no BreadcrumbList')
            continue
        vis = [norm(re.sub(r'<[^>]+>', '', x)) for x in re.findall(
            r'<li>(.*?)</li>', re.search(r'<nav class="crumbs"[^>]*><ol>(.*?)</ol>', s, re.S).group(1))]
        names = [x['name'] for x in crumb_ld['itemListElement']]
        if names != vis:
            bad.append(f'{lang}/{page}: JSON-LD names {names} != visible {vis}')
        want_lang = lang
        for it in crumb_ld['itemListElement']:
            item = it.get('item', '')
            if not item.startswith('https://noclaudkit.com/'):
                bad.append(f'{lang}/{page}: JSON-LD item not absolute canonical {item}')
            hl = site_lang(urlparse(item).path or '/')
            if hl and hl != want_lang:
                bad.append(f'{lang}/{page}: JSON-LD item cross-language {item}')
            if NB in it.get('name', ''):
                bad.append(f'{lang}/{page}: NBSP in JSON-LD name')
        if not crumb_ld['itemListElement'][-1]['item'].startswith('https://noclaudkit.com/pdf/'):
            bad.append(f'{lang}/{page}: last JSON-LD item is not this page\'s canonical')
        last_vis = re.search(r'<nav class="crumbs"[^>]*>.*?<span aria-current="page">', s, re.S)
        if not last_vis:
            bad.append(f'{lang}/{page}: last crumb is not a span')
        if re.search(r'[›/]\s*</', s) and 'crumbs' in s:
            # separators must not be HTML text; slash only in CSS
            crumb_txt = re.sub(r'<[^>]+>', '', re.search(r'<nav class="crumbs".*?</nav>', s, re.S).group(0))
            if '/' in crumb_txt or '›' in crumb_txt:
                bad.append(f'{lang}/{page}: breadcrumb separator character in HTML text')
        for a in re.findall(r'aria-label="([^"]*)"', s):
            if NB in html.unescape(a):
                bad.append(f'{lang}/{page}: NBSP in aria-label')
        for a in re.findall(r'\btitle="([^"]*)"', s):
            if NB in html.unescape(a):
                bad.append(f'{lang}/{page}: NBSP in title')
    if bad:
        for b in bad:
            fail(6, b)
    else:
        ok(6, 'breadcrumbs + valid BreadcrumbList JSON-LD on all 21 pages; names=visible; no NBSP in aria/title/JSON-LD')

def ac7():
    bad = []
    hosts = set()
    for lang, page, s in each_page():
        m = re.search(r'<meta http-equiv="Content-Security-Policy" content="([^"]*)">', s)
        if not m or m.group(1) != CSP:
            bad.append(f'{lang}/{page}: CSP changed')
        for val in re.findall(r'''\b(?:href|src|srcset)=["']([^"']+)["']''', s):
            u = urlparse(val)
            if u.scheme in ('http', 'https') and u.hostname:
                hosts.add(u.hostname)
        for j in re.findall(r'<script type="application/ld\+json">(.*?)</script>', s, re.S):
            for u in re.findall(r'https://([^/"\']+)', j):
                hosts.add(u)
    extra = hosts - ALLOWED_HOSTS
    if extra:
        bad.append(f'new external hosts: {sorted(extra)}')
    if bad:
        for b in bad:
            fail(7, b)
    else:
        ok(7, f'CSP meta byte-identical; hosts={sorted(hosts)}')

def ac8():
    before = {}
    for lang, page, s in each_page():
        before[path_of(lang, page)] = hashlib.sha256(s.encode()).hexdigest()
    before['sitemap.xml'] = hashlib.sha256(open('sitemap.xml', 'rb').read()).hexdigest()
    r = subprocess.run([sys.executable, 'tools/gen.py'], capture_output=True, text=True)
    if r.returncode != 0:
        fail(8, 'gen.py failed:\n' + r.stderr[-2000:])
        return
    changed = []
    for p, h in before.items():
        if hashlib.sha256(open(p, 'rb').read()).hexdigest() != h:
            changed.append(p)
    if changed:
        fail(8, 'generator rerun rewrote: ' + ', '.join(changed))
    else:
        ok(8, 'generator rerun = zero diff')

def ac9():
    bad = []
    for lang, page, s in each_page():
        canon = urlparse(CANON[lang])._replace(path=urlparse(CANON[lang]).path + ('' if page == 'index.html' else page)).geturl()
        # CANON already ends with /
        want = CANON[lang] + ('' if page == 'index.html' else page)
        m = re.search(r'<link rel="canonical" href="([^"]*)">', s)
        if not m or m.group(1) != want:
            bad.append(f'{lang}/{page}: canonical {m.group(1) if m else None} != {want}')
        alts = re.findall(r'<link rel="alternate" hreflang="([^"]*)" href="([^"]*)">', s)
        expect = [(HREFLANG[l], CANON[l] + ('' if page == 'index.html' else page)) for l in LANGS]
        expect.append(('x-default', CANON['en'] + ('' if page == 'index.html' else page)))
        if alts != expect:
            bad.append(f'{lang}/{page}: hreflang {alts} != {expect}')
        # exact head snippet form (one line of four alternates as gen.py emits)
        line = ''.join(f'<link rel="alternate" hreflang="{h}" href="{u}">' for h, u in expect)
        if line not in s:
            bad.append(f'{lang}/{page}: alternate tags not byte-identical to expected concatenation')
    if bad:
        for b in bad:
            fail(9, b)
    else:
        ok(9, 'canonical + hreflang byte-identical to the pre-interlinking scheme')

def extras():
    bad = []
    for lang, page, s in each_page():
        if 'PDF-инструменты' in s.replace('\u2011', '-'):
            bad.append(f'{lang}/{page}: PDF-инструменты still present')
        if re.search(r'\sstyle=', s):
            bad.append(f'{lang}/{page}: inline style=')
        scripts = re.findall(r'<script\b([^>]*)>', s)
        for attrs in scripts:
            typ = re.search(r'type="([^"]*)"', attrs)
            src = 'src=' in attrs
            if src:
                continue
            if not typ or typ.group(1) not in ('application/ld+json', 'application/json'):
                bad.append(f'{lang}/{page}: unexpected inline script {attrs}')
    if bad:
        for b in bad:
            fail('x', b)
    else:
        ok('x', 'no PDF-инструменты; no inline style; only JSON-LD / application/json inline scripts')

def main():
    ac1()
    print('SKIP AC2: home Popular links are out of scope for the pdf repo')
    ac3(); ac4(); ac5(); ac6(); ac7(); ac8(); ac9(); extras()
    print(f'\n{len(FAILS)} failed')
    sys.exit(1 if FAILS else 0)

if __name__ == '__main__':
    main()
